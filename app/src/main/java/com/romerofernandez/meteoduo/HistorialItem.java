package com.romerofernandez.meteoduo;

public class HistorialItem {

    public String puntoA;
    public String puntoB;
    public String fecha;
    public String jsonA;
    public String jsonB;

    public HistorialItem(String puntoA, String puntoB, String fecha,
                         String jsonA, String jsonB) {
        this.puntoA = puntoA;
        this.puntoB = puntoB;
        this.fecha = fecha;
        this.jsonA = jsonA;
        this.jsonB = jsonB;
    }
}
